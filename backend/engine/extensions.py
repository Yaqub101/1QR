"""Named building blocks an activity configuration can pick from.

ENGINE INTERNALS. A configuration refers to these by NAME (display_fields / effects / flag_rules in
activities.py); it never contains code. If an activity needs something that is not in these three
registries, STOP and ask: do not edit this file to suit one activity.

    DISPLAY_FIELDS  extra lines on the operator's student card
    EFFECTS         work done inside the confirm transaction, before the event is written; may add
                    to the event's details
    FLAG_RULES      may add a flag (e.g. LATE) to the event
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Callable, Optional

from sqlalchemy import text

from backend.engine.queries import active_completion, clock_text


@dataclass(frozen=True)
class DisplayField:
    label: str
    provider: Callable  # (conn, student: dict, ctx: EngineContext) -> Optional[str]


# ------------------------------------------------------------------ display fields
def _prn(conn, student, ctx):
    return student["prn"]


def _programme(conn, student, ctx):
    return student["programme"]


def _school(conn, student, ctx):
    return student["school"]


def _queue_position(conn, student, ctx):
    """The position the student holds, or the one they will get when confirmed."""
    held = conn.execute(text("SELECT queue_position FROM queue WHERE student_id = :s"), {"s": student["id"]}).scalar()
    if held is not None:
        return f"Position {held}"
    upcoming = conn.execute(text("SELECT coalesce(max(queue_position), 0) + 1 FROM queue")).scalar_one()
    return f"Position {upcoming} (when confirmed)"


def _thobe_issued(conn, student, ctx):
    allocation = active_completion(conn, student["id"], "THOBE_ALLOCATION")
    if allocation is None:
        return "Not on record yet"  # may simply not have synced from the Stadium yet
    return f"Yes — issued {clock_text(allocation['server_time'], ctx.settings.event_utc_offset_minutes)}"


def _eligibility(conn, student, ctx):
    returned = active_completion(conn, student["id"], "THOBE_RETURN")
    if returned is None:
        return "Robe return pending"
    if returned["kind"] == "WAIVER":
        return "Return waived by Admin"
    return f"Robe returned {clock_text(returned['server_time'], ctx.settings.event_utc_offset_minutes)}"


DISPLAY_FIELDS: dict[str, DisplayField] = {
    "prn": DisplayField("PRN", _prn),
    "programme": DisplayField("Programme", _programme),
    "school": DisplayField("School", _school),
    "queue_position": DisplayField("Queue position", _queue_position),
    "thobe_issued": DisplayField("Robe issued", _thobe_issued),
    "eligibility": DisplayField("Eligibility", _eligibility),
}


# ------------------------------------------------------------------ effects
def _enqueue(conn, student, ctx) -> dict:
    """Queue: take the next position from the shared counter, in the SAME transaction as the event
    (first come, first shown). The position is recorded on the event."""
    # The pipeline only reaches here when the student has NO active Queue completion. A queue row that is
    # still there therefore belongs to a completion an Admin reversed: drop it so the student is queued
    # again at the BACK (a new position), not blocked by the old row. (Concurrent confirms are still
    # settled by the unique index on the event, which rolls the loser's delete back too.)
    conn.execute(text("DELETE FROM queue WHERE student_id = :s"), {"s": student["id"]})
    position = conn.execute(
        text("INSERT INTO queue (student_id) VALUES (:s) RETURNING queue_position"), {"s": student["id"]}
    ).scalar_one()
    return {"queue_position": position}


EFFECTS: dict[str, Callable] = {"enqueue": _enqueue}  # (conn, student, ctx) -> dict merged into details


# ------------------------------------------------------------------ flag rules
def _late_registration(conn, student, ctx) -> Optional[str]:
    """Registration after the cutoff is accepted and flagged LATE (TODO Phase 7 assumption)."""
    late = conn.execute(text("SELECT late_cutoff IS NOT NULL AND now() > late_cutoff FROM settings")).scalar()
    return "LATE" if late else None


FLAG_RULES: dict[str, Callable] = {"late_registration": _late_registration}  # (conn, student, ctx) -> flag | None
